class HeadingsAreSeparated(unittest.TestCase):
    """Every heading needs a blank line above it, or Markdown renderers glue it
    to the preceding list."""

    def assert_headings_separated(self, out):
        lines = out.splitlines()
        for i, line in enumerate(lines):
            if line.startswith("#") and i > 0:
                self.assertEqual(
                    lines[i - 1], "",
                    "no blank line before %r (previous line %r)" % (line, lines[i - 1]))

    def test_voyager_block_then_next_model(self):
        out = uh.convert_voyager(
            "Firmware History\n\nV34: 2025-04-15\n"
            "  DM1x:\n   - Default CPU speed is back to 12MHz\n"
            "  DM16:\n   - Fixed internal RCL/STO calculation\n", VOY_URL)
        self.assert_headings_separated(out)

    def test_voyager_block_then_inline_label(self):
        out = uh.convert_voyager(
            "Firmware History\n\nV34: 2025-04-15\n"
            "  DM1x:\n   - Default CPU speed\n"
            "  DM41: Added Setup menu\n", VOY_URL)
        self.assert_headings_separated(out)

    def test_voyager_block_then_next_release(self):
        out = uh.convert_voyager(
            "Firmware History\n\nV34: 2025-04-15\n  DM1x:\n   - Speed\n"
            "\nV33: 2024-12-21\n  DM41: Fix\n", VOY_URL)
        self.assert_headings_separated(out)

    def test_voyager_bare_items_then_model(self):
        out = uh.convert_voyager(
            "Firmware History\n\nV26: 25.03.2018\n"
            "  New bold 7-segment font\n  DM41: Speed improvement\n", VOY_URL)
        self.assert_headings_separated(out)

    def test_html_bullets_then_sub_section(self):
        out = uh.convert_html(page(
            "<hr/>\n<h3>DM42n v3.26: 2025-11-14</h3>\n"
            "<ul><li>Upgrade Free42</li></ul>\n"
            '<div class="sub">DMCP5 changes</div>\n<ul><li>RESET+F4</li></ul>'), DM32_URL)
        self.assert_headings_separated(out)

    def test_html_bullets_then_next_release(self):
        out = uh.convert_html(page(
            "<hr/>\n<h3>DM32 v2.11:  2025-12-05</h3>\n<ul><li>One</li></ul>\n"
            "<hr/>\n<h3>DM32 v2.10:  2024-08-17</h3>\n<ul><li>Two</li></ul>"), DM32_URL)
        self.assert_headings_separated(out)


class HtmlMalformedMarkup(unittest.TestCase):
    """Upstream leaves <li> tags unclosed in places (DM42 has 155 <li> and 153
    </li>). Nothing may be dropped on the floor when that happens."""

    def bullets(self, body):
        out = uh.convert_html(page(
            "<hr/>\n<h3>DM32 v2.11:  2025-12-05</h3>\n" + body), DM32_URL)
        return [ln for ln in out.splitlines() if ln.startswith("- ")]

    def test_unclosed_li_followed_by_another_li(self):
        self.assertEqual(
            self.bullets("<ul><li>Fix: Crash in SHOW<li>Fix: INTEG_ down</li></ul>"),
            ["- Fix: Crash in SHOW", "- Fix: INTEG_ down"])

    def test_unclosed_li_at_end_of_list(self):
        self.assertEqual(self.bullets("<ul><li>PGMMENU patch</ul>"),
                         ["- PGMMENU patch"])

    def test_several_consecutive_unclosed_li(self):
        self.assertEqual(
            self.bullets("<ul><li>One<li>Two<li>Three</ul>"),
            ["- One", "- Two", "- Three"])

    def test_unclosed_li_before_a_sub_section(self):
        out = uh.convert_html(page(
            "<hr/>\n<h3>DM32 v2.11:  2025-12-05</h3>\n"
            "<ul><li>Register allocation patch</ul>\n"
            '<div class="sub">User Manual changes</div>\n'
            "<ul><li>Initial version</li></ul>"), DM32_URL)
        self.assertIn("- Register allocation patch", out.splitlines())
        self.assertIn("### User Manual changes", out.splitlines())
        self.assertIn("- Initial version", out.splitlines())

    def test_unclosed_li_before_next_release_heading(self):
        out = uh.convert_html(page(
            "<hr/>\n<h3>DM32 v2.11:  2025-12-05</h3>\n<ul><li>Kept item\n"
            "<hr/>\n<h3>DM32 v2.10:  2024-08-17</h3>\n<ul><li>Later item</li></ul>"),
            DM32_URL)
        lines = out.splitlines()
        self.assertIn("- Kept item", lines)
        self.assertIn("- Later item", lines)
        self.assertLess(lines.index("- Kept item"), lines.index("## DM32 v2.10 — 2024-08-17"))
