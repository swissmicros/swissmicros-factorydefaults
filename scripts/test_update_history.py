#!/usr/bin/env python3
"""Tests for update-history.py.

Run with:  python3 -m unittest discover scripts

The converters are pure str -> str, so everything here runs offline against
small fixtures. The network fetch lives behind its own function and is not
exercised.
"""

import importlib.util
import pathlib
import unittest


def _load():
    """Import the hyphenated sibling module by path."""
    path = pathlib.Path(__file__).with_name("update-history.py")
    spec = importlib.util.spec_from_file_location("update_history", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


uh = _load()

DM32_URL = "https://technical.swissmicros.com/dm32/firmware/history.html"
VOY_URL = "https://technical.swissmicros.com/voyager/firmware/history.txt"
DMCP5 = uh.Platform("DMCP5", "../DMCP5_HISTORY.md",
                    "https://technical.swissmicros.com/dmcp/firmware_dmcp5/history.html")


def page(body):
    """Wrap a body fragment in the chrome every upstream page carries."""
    return (
        '<!DOCTYPE html>\n<html lang="en">\n<head>\n'
        '<title>Firmware History</title>\n'
        '<link rel="stylesheet" href="/mod_autoindex/style.css" type="text/css" />\n'
        "<style>\na { text-decoration: underline; }\n</style>\n"
        "</head>\n<body>\n"
        '<div class="header">\n<h1>DM32 Program Firmware History</h1>\n</div>\n'
        "<br/>\n"
        '<div class="highlighted">\n'
        "Please remember it is always wise to make FAT disk backup before any update.\n"
        "</div>\n<br/>\n<!-- Last changes here -->\n"
        + body +
        "\n</body>\n</html>\n"
    )


class HtmlDocumentShape(unittest.TestCase):

    def test_h1_becomes_title(self):
        out = uh.convert_html(page("<hr/>\n<h3>DM32 v2.11:  2025-12-05</h3>"), DM32_URL)
        self.assertTrue(out.startswith("# DM32 Program Firmware History\n"))

    def test_banner_names_the_source_url(self):
        out = uh.convert_html(page("<hr/>\n<h3>DM32 v2.11:  2025-12-05</h3>"), DM32_URL)
        self.assertIn("Generated by scripts/update-history.py", out)
        self.assertIn(DM32_URL, out)
        self.assertIn("Do not edit by hand", out)

    def test_highlighted_div_becomes_blockquote(self):
        out = uh.convert_html(page("<hr/>\n<h3>DM32 v2.11:  2025-12-05</h3>"), DM32_URL)
        self.assertIn(
            "> Please remember it is always wise to make FAT disk backup before any update.",
            out)

    def test_platform_link_emitted_when_given(self):
        out = uh.convert_html(page("<hr/>\n<h3>DM32 v2.11:  2025-12-05</h3>"),
                              DM32_URL, platform=DMCP5)
        self.assertIn("[DMCP5 system firmware history](../DMCP5_HISTORY.md)", out)
        self.assertIn(DMCP5.url, out)

    def test_no_platform_link_when_absent(self):
        out = uh.convert_html(page("<hr/>\n<h3>DM32 v2.11:  2025-12-05</h3>"), DM32_URL)
        self.assertNotIn("Platform firmware:", out)

    def test_noise_is_dropped(self):
        out = uh.convert_html(page(
            "<hr/>\n<p>&nbsp;</p>\n<br/>\n<h3>DM32 v2.11:  2025-12-05</h3>\n<p>&nbsp;</p>"),
            DM32_URL)
        for noise in ("<hr", "<br", "&nbsp;", "<style", "stylesheet",
                      "Last changes here", "<!DOCTYPE"):
            self.assertNotIn(noise, out)

    def test_output_is_deterministic(self):
        html = page("<hr/>\n<h3>DM32 v2.11:  2025-12-05</h3>\n"
                    '<div class="sub">Fixes</div>\n<ul><li>One</li></ul>')
        self.assertEqual(uh.convert_html(html, DM32_URL),
                         uh.convert_html(html, DM32_URL))

    def test_trailing_newline_exactly_one(self):
        out = uh.convert_html(page("<hr/>\n<h3>DM32 v2.11:  2025-12-05</h3>"), DM32_URL)
        self.assertTrue(out.endswith("\n"))
        self.assertFalse(out.endswith("\n\n"))


class HtmlReleaseHeadings(unittest.TestCase):

    def heading(self, h3):
        out = uh.convert_html(page("<hr/>\n<h3>%s</h3>" % h3), DM32_URL)
        return [ln for ln in out.splitlines() if ln.startswith("## ")]

    def test_plain_heading_uses_em_dash(self):
        self.assertEqual(self.heading("DM32 v2.11:  2025-12-05"),
                         ["## DM32 v2.11 — 2025-12-05"])

    def test_single_space_after_colon(self):
        self.assertEqual(self.heading("DM32 v2.03: 2023-06-15"),
                         ["## DM32 v2.03 — 2023-06-15"])

    def test_space_before_colon(self):
        self.assertEqual(self.heading("DM32 v2.02 : 2023-05-21"),
                         ["## DM32 v2.02 — 2023-05-21"])

    def test_keeps_built_with_parenthetical(self):
        self.assertEqual(self.heading("DM42n v3.26 (built with DMCP5 3.55): 2025-11-14"),
                         ["## DM42n v3.26 (built with DMCP5 3.55) — 2025-11-14"])

    def test_slash_date_normalises_to_iso(self):
        self.assertEqual(self.heading("DMCP v3.8 : 2018/07/03"),
                         ["## DMCP v3.8 — 2018-07-03"])

    def test_heading_without_model_name(self):
        self.assertEqual(self.heading("v3.0 : 2017/12/08"),
                         ["## v3.0 — 2017-12-08"])

    def test_trailing_whitespace_after_date(self):
        self.assertEqual(self.heading("DMCP v3.20: 2020-10-09 "),
                         ["## DMCP v3.20 — 2020-10-09"])

    def test_non_release_heading_passes_through(self):
        self.assertEqual(self.heading("End of Beta Phase"), ["## End of Beta Phase"])

    def test_upstream_typo_preserved_verbatim(self):
        self.assertEqual(self.heading("DM42 v3.10 (bult with DMCP 3.10): 2018-10-01"),
                         ["## DM42 v3.10 (bult with DMCP 3.10) — 2018-10-01"])


class HtmlSections(unittest.TestCase):

    def test_sub_div_becomes_h3(self):
        out = uh.convert_html(page(
            "<hr/>\n<h3>DM32 v2.11:  2025-12-05</h3>\n"
            '<div class="sub">Fixes</div>\n<ul><li>One</li></ul>'), DM32_URL)
        self.assertIn("### Fixes", out)

    def test_sub_label_is_free_text_not_an_enum(self):
        out = uh.convert_html(page(
            "<hr/>\n<h3>DM32 v2.11:  2025-12-05</h3>\n"
            '<div class="sub">User Manual updates in chapters</div>\n<ul><li>One</li></ul>'),
            DM32_URL)
        self.assertIn("### User Manual updates in chapters", out)

    def test_release_without_sub_label_emits_bullets_directly(self):
        out = uh.convert_html(page(
            "<hr/>\n<h3>DM42n v3.26 (built with DMCP5 3.55): 2025-11-14</h3>\n"
            "<ul>\n  <li>Upgrade Free42 core library to 3.3.10 version</li>\n</ul>"),
            DM32_URL)
        self.assertNotIn("###", out)
        lines = [ln for ln in out.splitlines() if ln.strip()]
        i = lines.index("## DM42n v3.26 (built with DMCP5 3.55) — 2025-11-14")
        self.assertEqual(lines[i + 1], "- Upgrade Free42 core library to 3.3.10 version")

    def test_unlabelled_bullets_then_labelled_section(self):
        out = uh.convert_html(page(
            "<hr/>\n<h3>DM42n v3.26 (built with DMCP5 3.55): 2025-11-14</h3>\n"
            "<ul>\n  <li>Upgrade Free42 core library</li>\n</ul>\n"
            '<div class="sub">DMCP5 changes</div>\n'
            "<ul>\n  <li>RESET+F4 activates bootloader (USB DFU)</li>\n</ul>"), DM32_URL)
        lines = [ln for ln in out.splitlines() if ln.strip()]
        self.assertLess(lines.index("- Upgrade Free42 core library"),
                        lines.index("### DMCP5 changes"))
        self.assertIn("- RESET+F4 activates bootloader (USB DFU)", lines)


class HtmlBullets(unittest.TestCase):

    def bullets(self, li):
        out = uh.convert_html(page(
            "<hr/>\n<h3>DM32 v2.11:  2025-12-05</h3>\n"
            '<div class="sub">Fixes</div>\n<ul>%s</ul>' % li), DM32_URL)
        return [ln for ln in out.splitlines() if ln.startswith("- ")]

    def test_anchor_becomes_markdown_link(self):
        self.assertEqual(
            self.bullets('<li>Fixed a crash '
                         '(<a href="https://forum.swissmicros.com/v.php?f=33&amp;t=4159">forum</a>)</li>'),
            ["- Fixed a crash ([forum](https://forum.swissmicros.com/v.php?f=33&t=4159))"])

    def test_bare_url_left_as_text(self):
        self.assertEqual(
            self.bullets("<li>Fixed div, mul (forum https://www.hpmuseum.org/forum/thread-24155.html)</li>"),
            ["- Fixed div, mul (forum https://www.hpmuseum.org/forum/thread-24155.html)"])

    def test_entities_are_unescaped(self):
        self.assertEqual(self.bullets("<li>STAT ERROR &amp; INVALID y^x</li>"),
                         ["- STAT ERROR & INVALID y^x"])

    def test_hard_wrapped_li_collapses_to_one_line(self):
        self.assertEqual(
            self.bullets("<li>Fixed: crash after using equation solver with Flag-11\n"
                         "(see the forum)</li>"),
            ["- Fixed: crash after using equation solver with Flag-11 (see the forum)"])

    def test_quotes_preserved(self):
        self.assertEqual(
            self.bullets('<li>improved glyphs in the SwissKeys font (the "bold" font).</li>'),
            ['- improved glyphs in the SwissKeys font (the "bold" font).'])


