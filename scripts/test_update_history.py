class VoyagerLabelRule(unittest.TestCase):
    """A colon does not make a model label. These are the traps in the source."""

    def body(self, src):
        out = uh.convert_voyager("Firmware History\n\nV26: 25.03.2018\n" + src, VOY_URL)
        head = out.index("## ")
        return [ln for ln in out[head:].splitlines() if ln.strip()]

    def test_bugfix_prefix_is_not_a_model(self):
        self.assertEqual(
            self.body("  Bugfix: MEM output fixed in DM15_M80 and DM15_M1B\n"),
            ["## V26 — 2018-03-25", "- Bugfix: MEM output fixed in DM15_M80 and DM15_M1B"])

    def test_gto_prefix_is_not_a_model(self):
        self.assertEqual(self.body("  GTO I: extended range to 999\n"),
                         ["## V26 — 2018-03-25", "- GTO I: extended range to 999"])

    def test_all_is_a_model_label(self):
        self.assertEqual(self.body("  ALL: Lowered consumption in serial console\n"),
                         ["## V26 — 2018-03-25", "### ALL", "- Lowered consumption in serial console"])

    def test_dmxx_is_a_model_label(self):
        self.assertEqual(self.body("  DMXX: Fixed julian date\n"),
                         ["## V26 — 2018-03-25", "### DMXX", "- Fixed julian date"])

    def test_slash_label_is_a_model_label(self):
        self.assertEqual(self.body("  DM15/16:\n   - New 2-line mode\n"),
                         ["## V26 — 2018-03-25", "### DM15/16", "- New 2-line mode"])

    def test_underscore_label_is_a_model_label(self):
        self.assertEqual(self.body("  DM15_M80: Change initial register allocation\n"),
                         ["## V26 — 2018-03-25", "### DM15_M80", "- Change initial register allocation"])

    def test_mixed_case_label_is_a_model_label(self):
        self.assertEqual(self.body("  DM1X: fixed PSE\n"),
                         ["## V26 — 2018-03-25", "### DM1X", "- fixed PSE"])

    def test_dash_separator_is_a_model_label(self):
        """V27 writes "DM41 - Fixed ..." instead of "DM41: Fixed ..."."""
        self.assertEqual(self.body("  DM41 - Fixed continuous stopwatch operation\n"),
                         ["## V26 — 2018-03-25", "### DM41",
                          "- Fixed continuous stopwatch operation"])

    def test_space_only_label_stays_bare_text(self):
        """V21 writes "DM1X fixed PSE" with no separator. Inferring a label there
        would be guesswork, so the line passes through intact."""
        self.assertEqual(
            self.body("  DM1X fixed PSE (keep any button pressed to interrupt)\n"),
            ["## V26 — 2018-03-25",
             "- DM1X fixed PSE (keep any button pressed to interrupt)"])

    def test_dash_inside_prose_is_not_a_label_split(self):
        self.assertEqual(
            self.body("  Changed init after reset - more battery friendly\n"),
            ["## V26 — 2018-03-25",
             "- Changed init after reset - more battery friendly"])


class VoyagerAnnotationsAndEscaping(unittest.TestCase):

    def test_removal_annotation_attaches_to_its_release(self):
        out = uh.convert_voyager(
            "Firmware History\n\n"
            "!!! V30 firmware was removed after confirmation of excessive consumption in OFF mode\n"
            "V30: 17.01.2020\n  ALL: Added 'bootloader' serial console command\n", VOY_URL)
        lines = [ln for ln in out.splitlines() if ln.strip()]
        i = lines.index("## V30 — 2020-01-17")
        self.assertEqual(
            lines[i + 1],
            "> !!! V30 firmware was removed after confirmation of excessive "
            "consumption in OFF mode")

    def test_asterisks_are_escaped(self):
        out = uh.convert_voyager(
            "Firmware History\n\nV16: 13.02.2014\n"
            "  *** this will be the last firmware version <32k ***\n", VOY_URL)
        self.assertIn(r"- \*\*\* this will be the last firmware version \<32k \*\*\*", out)

    def test_backtick_is_escaped(self):
        out = uh.convert_voyager("Firmware History\n\nV1: 10.2.2012\n  use `x` here\n", VOY_URL)
        self.assertIn(r"- use \`x\` here", out)

    def test_brackets_are_left_readable(self):
        out = uh.convert_voyager(
            "Firmware History\n\nV6: 1.7.2012\n"
            "  ALL: switch to 12MHz and back with [ON]+[9]\n", VOY_URL)
        self.assertIn("- switch to 12MHz and back with [ON]+[9]", out)


